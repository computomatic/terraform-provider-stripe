package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/computomatic/terraform-provider-stripe/internal/fields"
)

const header = "// Code generated by tools/schemagen from spec/openapi.json; DO NOT EDIT.\n\n"

var shapeNames = map[fields.Shape]string{
	fields.String:     "String",
	fields.Bool:       "Bool",
	fields.Int:        "Int",
	fields.Float:      "Float",
	fields.Object:     "Object",
	fields.ObjectList: "ObjectList",
	fields.ScalarList: "ScalarList",
	fields.ScalarSet:  "ScalarSet",
	fields.ObjectMap:  "ObjectMap",
	fields.StringMap:  "StringMap",
}

// RenderTable renders the Go source of a resource's field table.
func RenderTable(pkg string, table []fields.Field) ([]byte, error) {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "// Package %s holds the field table of the Stripe %s object.\npackage %s\n\n", pkg, pkg, pkg)
	b.WriteString("import \"github.com/computomatic/terraform-provider-stripe/internal/fields\"\n\n")
	b.WriteString("// Table lists every request and response field of the object.\n")
	b.WriteString("var Table = ")
	writeFields(&b, table)
	b.WriteString("\n")
	return gofmt(b.String())
}

// RenderVersion renders the file that holds the pinned API version.
func RenderVersion(version string) ([]byte, error) {
	src := header + "package stripeapi\n\n" +
		"// Version is the Stripe API version the provider pins. It is sent on every request.\n" +
		"// It is read from spec/PIN.json, so the generated field tables and the header agree.\n" +
		"const Version = " + strconv.Quote(version) + "\n"
	return gofmt(src)
}

func gofmt(src string) ([]byte, error) {
	out, err := format.Source(bytes.NewBufferString(src).Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return out, nil
}

func writeFields(b *strings.Builder, table []fields.Field) {
	b.WriteString("[]fields.Field{\n")
	for _, f := range table {
		writeField(b, f)
	}
	b.WriteString("}")
}

func writeField(b *strings.Builder, f fields.Field) {
	b.WriteString("{")
	fmt.Fprintf(b, "Name: %s, Shape: fields.%s", strconv.Quote(f.Name), shapeNames[f.Shape])
	if f.Shape == fields.ScalarList || f.Shape == fields.ScalarSet {
		fmt.Fprintf(b, ", Elem: fields.%s", shapeNames[f.Elem])
	}
	for _, flag := range []struct {
		name string
		on   bool
	}{
		{"Required", f.Required},
		{"Create", f.Create},
		{"Update", f.Update},
		{"Response", f.Response},
		{"ServerDefaulted", f.ServerDefaulted},
	} {
		if flag.on {
			fmt.Fprintf(b, ", %s: true", flag.name)
		}
	}
	if len(f.Enum) > 0 {
		b.WriteString(", Enum: []string{")
		for i, e := range f.Enum {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(e))
		}
		b.WriteString("}")
	}
	if f.Description != "" {
		fmt.Fprintf(b, ", Description: %s", strconv.Quote(f.Description))
	}
	if len(f.Fields) > 0 {
		b.WriteString(", Fields: ")
		writeFields(b, f.Fields)
	}
	b.WriteString("},\n")
}
