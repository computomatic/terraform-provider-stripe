const (
	importBlockURL  = "https://developer.hashicorp.com/terraform/language/import"
	timeoutsURL     = "https://developer.hashicorp.com/terraform/language/resources/syntax#operation-timeouts"
	removedBlockURL = "https://developer.hashicorp.com/terraform/language/block/removed"
)

var (
	whitespaceLines = regexp.MustCompile(`\s*\n\s*`)
	markdownLink    = regexp.MustCompile(`\[([^\]]*)\]\([^)]*\)`)
)

// example is a Terraform configuration shown on a page.
type example struct {
	// Title heads the example under `### `. It is empty for the main example.
	Title string
	Code  string
}

// importExample is what a resource's import.sh states.
type importExample struct {
	// Lead is the comment line above the command, a sentence about the ID. It may be empty.
	Lead string
	// Name is the resource name in the command, such as `launch`.
	Name string
	ID   string
}

// pageInput is what a page needs besides the schema.
type pageInput struct {
	Examples []example
	Import   *importExample
	// DataSources are every data source, by type, which an embedded copy's subsection links to
	// when that data source holds every attribute of the copy.
	DataSources map[string]*schema
	// Guides maps a top-level nested attribute moved off the page, because the page would pass
	// the budget, to the name of the guide page that holds its subsections (D3).
	Guides map[string]string
}

// removalSentence follows the default statement of a resource's Optional and Computed argument
// (ADR 2026-10-29-full-attribute-coverage, D4 and E2).
const removalSentence = "Removing it from the configuration leaves the current value."

// page writes the lines and subsections of one page.
type page struct {
	*markdown
	in pageInput
	// resource says the page is a resource's, whose Optional and Computed arguments keep their
	// value when the configuration removes them.
	resource bool
}

// markdown builds a page from blocks separated by one blank line.
type markdown struct {
	blocks []string
}

func (m *markdown) add(block string) { m.blocks = append(m.blocks, block) }

func (m *markdown) String() string { return strings.Join(m.blocks, "\n\n") + "\n" }

// lines joins list items or other consecutive lines into one block.
func lines(l ...string) string { return strings.Join(l, "\n") }

func fence(lang, code string) string {
	return "```" + lang + "\n" + strings.TrimRight(code, "\n") + "\n```"
}

func oneLine(s string) string {
	return strings.TrimSpace(whitespaceLines.ReplaceAllString(s, " "))
}

// plainText is s without Markdown links and code spans, for the front matter.
func plainText(s string) string {
	s = markdownLink.ReplaceAllString(s, "$1")
	return strings.ReplaceAll(s, "`", "")
}

func frontMatter(title, description string) string {
	first, _, _ := strings.Cut(strings.TrimSpace(description), "\n\n")
	return lines(
		"---",
		"# generated by tools/docgen",
		fmt.Sprintf("page_title: %q", title),
		`subcategory: ""`,
		"description: |-",
		"  "+plainText(oneLine(first)),
		"---",
	)
}

// markers is the parenthesised prefix of a line: the kind (when labelled) and the flags.
func markers(a *attr, labelled bool) string {
	var m []string
	if labelled {
		switch {
		case a.Required:
			m = append(m, "Required")
		case a.Optional:
			m = append(m, "Optional")
		default:
			m = append(m, "Read-Only")
		}
	}
	if a.Sensitive {
		m = append(m, "Sensitive")
	}
	if a.WriteOnly {
		m = append(m, "Write-Only")
	}
	if a.Deprecated {
		m = append(m, "Deprecated")
	}
	if len(m) == 0 {
		return ""
	}
	return "(" + strings.Join(m, ", ") + ")"
}

// line is one bullet. Its link to a nested attribute's subsection uses the dotted path. An
// optional argument's line ends with its default statement and, on a resource page where it
// is also Computed, the removal sentence (D4).
func (p *page) line(a *attr, path string, labelled bool) string {
	parts := []string{"*", "`" + a.Name + "`", "-"}
	if m := markers(a, labelled); m != "" {
		parts = append(parts, m)
	}
	d := oneLine(a.Description)
	var after []string
	if labelled && a.Optional && !a.Required {
		if a.Default != "" {
			after = append(after, a.Default)
		}
		if p.resource && a.Computed {
			after = append(after, removalSentence)
		}
	}
	// A sentence that follows a description Stripe left without a full stop needs one.
	if d != "" && len(after) > 0 && !strings.ContainsAny(d[len(d)-1:], ".!?") {
		d += "."
	}
	if d != "" {
		parts = append(parts, d)
	}
	parts = append(parts, after...)
	if a.Nesting != nestNone {
		if g, ok := p.in.Guides[path]; ok {
			parts = append(parts, fmt.Sprintf("See [`%s`](../guides/%s) on its own page.", path, g))
		} else {
			parts = append(parts, fmt.Sprintf("See [`%s`](#%s) below.", path, path))
		}
	}
	return strings.Join(parts, " ")
}

func (p *page) lineList(attrs []*attr, labelled bool) string {
	l := make([]string, len(attrs))
	for i, a := range attrs {
		l[i] = p.line(a, a.Name, labelled)
	}
	return strings.Join(l, "\n")
}

// subsections writes a `###` subsection for each nested attribute, each followed by those
// of its own nested attributes. labelled says whether the attribute is set by the user. An
// attribute moved to a guide page has none here, and an embedded copy whose data source holds
// every attribute it has is one line linking to that data source's page (D3).
func (p *page) subsections(attrs []*attr, prefix string, labelled bool) {
	for _, a := range attrs {
		if a.Nesting == nestNone {
			continue
		}
		path := prefix + a.Name
		if _, moved := p.in.Guides[path]; moved {
			continue
		}
		inner := labelled && a.argument()
		p.add(fmt.Sprintf("<a id=%q></a>\n### `%s`", path, path))
		var byline, each string
		switch a.Nesting {
		case nestSingle:
			byline = fmt.Sprintf("The `%s` attribute supports:", path)
			each = fmt.Sprintf("The `%s` attribute holds", path)
		case nestList:
			byline = fmt.Sprintf("The `%s` attribute is a list. Each element supports:", path)
			each = fmt.Sprintf("The `%s` attribute is a list. Each element holds", path)
		case nestSet:
			byline = fmt.Sprintf("The `%s` attribute is a set. Each element supports:", path)
			each = fmt.Sprintf("The `%s` attribute is a set. Each element holds", path)
		case nestMap:
			byline = fmt.Sprintf("The `%s` attribute is a map. Each value supports:", path)
			each = fmt.Sprintf("The `%s` attribute is a map. Each value holds", path)
		}
		if ds := p.in.DataSources[a.Copy]; ds != nil {
			// A copy carries the copied object's `object`, its type's name, which a data source
			// does not.
			copied := filter(a.Children, func(c *attr) bool { return c.Name != "object" || at(ds.Attrs, "object") != nil })
			if holds(ds.Attrs, copied) {
				also := ""
				if len(copied) < len(a.Children) {
					also = " and `object`, the name of its type"
				}
				p.add(fmt.Sprintf("%s %s, with the attributes of the [`%s`](../data-sources/%s) data source%s.", each, engine.WithArticle(engine.Noun(a.Copy)), a.Copy, strings.TrimPrefix(a.Copy, "stripe_"), also))
				continue
			}
		}
		p.add(byline)
		if len(a.Children) > 0 {
			l := make([]string, len(a.Children))
			for i, c := range a.Children {
				l[i] = p.line(c, path+"."+c.Name, inner)
			}
			p.add(strings.Join(l, "\n"))
		}
		p.subsections(a.Children, path+".", inner)
	}
}

// holds reports whether a data source's attributes include every attribute of a copy, at every
// depth, so that its page documents the whole copy.
func holds(ds, copied []*attr) bool {
	for _, c := range copied {
		d := at(ds, c.Name)
		if d == nil || (c.Nesting == nestNone) != (d.Nesting == nestNone) || !holds(d.Children, c.Children) {
			return false
		}
	}
	return true
}

// exampleUsage writes the Example Usage section.
func exampleUsage(m *page, examples []example) error {
	if len(examples) == 0 {
		return fmt.Errorf("no example")
	}
	m.add("## Example Usage")
	for _, e := range examples {
		if e.Title != "" {
			m.add("### " + e.Title)
		}
		m.add(fence("terraform", e.Code))
	}
	return nil
}

func filter(attrs []*attr, keep func(*attr) bool) []*attr {
	var out []*attr
	for _, a := range attrs {
		if keep(a) {
			out = append(out, a)
		}
	}
	return out
}

// argumentSections writes the Argument Reference of a resource or the provider, and the
// subsections of its nested arguments.
func argumentSections(m *page, args []*attr, byline string) {
	if len(args) == 0 {
		return
	}
	m.add("## Argument Reference")
	m.add(byline)
	m.add(m.lineList(args, true))
	m.subsections(args, "", true)
}

// resourceArguments writes the required and optional arguments in two lists.
func resourceArguments(m *page, s *schema) []*attr {
	args := filter(s.Attrs, func(a *attr) bool { return a.argument() && a.Name != "timeouts" })
	if len(args) == 0 {
		return nil
	}
	required := filter(args, func(a *attr) bool { return a.Required })
	optional := filter(args, func(a *attr) bool { return !a.Required })
	m.add("## Argument Reference")
	if len(required) > 0 {
		m.add("The following arguments are required:")
		m.add(m.lineList(required, true))
	}
	if len(optional) > 0 {
		m.add("The following arguments are optional:")
		m.add(m.lineList(optional, true))
	}
	m.subsections(args, "", true)
	return args
}

// attributeSections writes the Attribute Reference. The subsections of its nested
// attributes follow the list.
func attributeSections(m *page, kind string, exported []*attr, haveArguments bool) {
	m.add("## Attribute Reference")
	if len(exported) == 0 {
		m.add(fmt.Sprintf("This %s exports no additional attributes.", kind))
		return
	}
	if haveArguments {
		m.add(fmt.Sprintf("This %s exports the following attributes in addition to the arguments above:", kind))
	} else {
		m.add(fmt.Sprintf("This %s exports the following attributes:", kind))
	}
	m.add(m.lineList(exported, false))
	m.subsections(exported, "", false)
}

// idAttribute is the `id` line of the Attribute Reference. A resource that lets the user
// choose its ID exports it too, described as the Stripe ID.
func idAttribute(s *schema) *attr {
	id := s.find("id")
	if id == nil {
		return nil
	}
	if id.argument() {
		return &attr{Name: "id", Description: "The Stripe ID of the object."}
	}
	return id
}

func timeoutsSection(m *page, s *schema, defaultTimeout time.Duration) {
	t := s.find("timeouts")
	if t == nil {
		return
	}
	def := strings.TrimSuffix(defaultTimeout.String(), "0s")
	m.add("## Timeouts")
	m.add(fmt.Sprintf("[Configuration options](%s) are set with the `timeouts` attribute, for example `timeouts = { create = \"5m\" }`:", timeoutsURL))
	l := make([]string, len(t.Children))
	for i, c := range t.Children {
		l[i] = fmt.Sprintf("* `%s` - (Default `%s`)", c.Name, def)
	}
	m.add(strings.Join(l, "\n"))
}

func renderResource(s *schema, in pageInput, defaultTimeout time.Duration) (string, error) {
	if in.Import == nil {
		return "", fmt.Errorf("no import example")
	}
	m := &page{markdown: &markdown{}, in: in, resource: true}
	m.add(frontMatter(s.Type+" Resource - Stripe", s.Description))
	m.add("# Resource: " + s.Type)
	m.add(strings.TrimSpace(s.Description))
	if s.MoneyNote != "" {
		m.add(engine.NoteWarning.Sigil() + " " + s.MoneyNote)
	}
	if s.DestroyNote != "" {
		m.add(engine.NoteWarning.Sigil() + " " + s.DestroyNote)
	}
	if err := exampleUsage(m, in.Examples); err != nil {
		return "", err
	}
	args := resourceArguments(m, s)
	var exported []*attr
	if id := idAttribute(s); id != nil {
		exported = append(exported, id)
	}
	exported = append(exported, filter(s.Attrs, func(a *attr) bool {
		return !a.argument() && a.Name != "id" && a.Name != "timeouts"
	})...)
	attributeSections(m, "resource", exported, len(args) > 0)
	timeoutsSection(m, s, defaultTimeout)
	if s.DestroyNote != "" {
		removingSection(m, s, in.Import.Name)
	}
	if err := importSection(m, s, *in.Import); err != nil {
		return "", err
	}
	return m.String(), nil
}

func renderDataSource(s *schema, in pageInput) (string, error) {
	m := &page{markdown: &markdown{}, in: in}
	m.add(frontMatter(s.Type+" Data Source - Stripe", s.Description))
	m.add("# Data Source: " + s.Type)
	m.add(strings.TrimSpace(s.Description))
	if err := exampleUsage(m, in.Examples); err != nil {
		return "", err
	}
	args := filter(s.Attrs, func(a *attr) bool { return a.argument() })
	if len(args) > 0 {
		m.add("## Argument Reference")
		m.add("This data source supports the following arguments:")
		required := filter(args, func(a *attr) bool { return a.Required })
		listParams := filter(args, func(a *attr) bool { return slices.Contains(s.ListParams, a.Name) })
		optional := filter(args, func(a *attr) bool { return !a.Required && !slices.Contains(s.ListParams, a.Name) })
		// The required arguments name a parent and the list parameters choose the parent's list.
		// Only the other optional ones are lookup keys.
		if len(optional) > 1 {
			m.add("Exactly one must be set.")
		} else {
			// The schema marks the lone key Optional, but a block must set exactly one key.
			for _, a := range optional {
				c := *a
				c.Required, c.Optional = true, false
				required = append(required, &c)
			}
			optional = nil
		}
		m.add(m.lineList(append(append(required, optional...), listParams...), true))
		m.subsections(args, "", true)
	}
	exported := filter(s.Attrs, func(a *attr) bool { return !a.argument() })
	attributeSections(m, "data source", exported, len(args) > 0)
	return m.String(), nil
}

// providerProse is the hand-written text of the provider page.
type providerProse struct {
	// FrontMatter is the page's front matter, without the generated comment.
	FrontMatter string
	// Lead is the text before the first `##` heading.
	Lead string
	// Sections are the `##` sections that follow Example Usage, with the placeholder
	// `<!-- provider-description -->` replaced by the provider schema's description.
	Sections string
}

func renderProvider(s *schema, prose providerProse, examples []example) (string, error) {
	m := &page{markdown: &markdown{}}
	m.add(prose.FrontMatter)
	m.add(strings.TrimSpace(prose.Lead))
	if err := exampleUsage(m, examples); err != nil {
		return "", err
	}
	m.add(strings.TrimSpace(strings.ReplaceAll(prose.Sections, "<!-- provider-description -->", strings.TrimSpace(s.Description))))
	argumentSections(m, s.Attrs, "This provider supports the following arguments:")
	return m.String(), nil
}

// removingSection shows how to stop managing an object whose destroy is refused: a `removed`
// block, or `terraform state rm`. name is the resource name the Import section uses.
func removingSection(m *page, s *schema, name string) {
	subject := engine.Noun(s.Type)
	address := s.Type + "." + name
	m.add("## Removing from State")
	m.add(fmt.Sprintf("To stop managing %s whose destroy is refused, remove it from the state without destroying it. In Terraform 1.7 and later, and OpenTofu 1.10 and later, replace the `resource` block with a [`removed` block](%s) and apply:", engine.WithArticle(subject), removedBlockURL))
	m.add(fence("terraform", fmt.Sprintf("removed {\n  from = %s\n\n  lifecycle {\n    destroy = false\n  }\n}", address)))
	m.add("Using `terraform state rm`:")
	m.add(fence("console", "% terraform state rm "+address))
	m.add(fmt.Sprintf("The %s stays in the Stripe account. Replacing one with `terraform apply -replace` or `terraform taint` fails in the same way, at apply.", subject))
}

func importSection(m *page, s *schema, imp importExample) error {
	name := s.Type + "." + imp.Name
	subject := engine.Noun(s.Type)
	indefinite := engine.WithArticle(subject)
	id := imp.ID
	m.add("## Import")
	if imp.Lead != "" {
		m.add(imp.Lead)
	}
	m.add(fmt.Sprintf("In Terraform v1.5.0 and later, and in OpenTofu, use an [`import` block](%s) to import %s using its ID. For example:", importBlockURL, indefinite))
	m.add(fence("terraform", fmt.Sprintf("import {\n  to = %s\n  id = %q\n}", name, id)))

	var parent *identityAttr
	for _, a := range s.Identity {
		if a.Name != "id" {
			parent = a
		}
	}
	if len(s.Identity) > 0 {
		body := fmt.Sprintf("  id = %q", id)
		if parent != nil {
			p, child, ok := strings.Cut(id, "/")
			if !ok {
				return fmt.Errorf("import ID %q has no parent part for the identity attribute %s", id, parent.Name)
			}
			body = fmt.Sprintf("  %s = %q\n  id%s = %q", parent.Name, p, strings.Repeat(" ", len(parent.Name)-2), child)
		}
		m.add("In Terraform v1.12.0 and later, and in OpenTofu v1.12.0 and later, the `import` block can use the `identity` attribute instead. For example:")
		m.add(fence("terraform", fmt.Sprintf("import {\n  to = %s\n  identity = {\n%s\n  }\n}", name, indent(body, "  "))))
		m.add("### Identity Schema")
		identitySection(m, s.Identity, subject)
	}
	m.add(fmt.Sprintf("Using `terraform import`, import %s using its ID. For example:", indefinite))
	m.add(fence("console", "% terraform import "+name+" "+id))
	if s.ImportNote != "" {
		m.add(s.ImportNoteLevel.Sigil() + " " + strings.TrimSpace(s.ImportNote))
	}
	return nil
}

func indent(s, prefix string) string {
	return prefix + strings.ReplaceAll(s, "\n", "\n"+prefix)
}

func identitySection(m *page, ids []*identityAttr, subject string) {
	describe := func(a *identityAttr) string {
		switch {
		case a.Description != "":
			return a.Description
		case a.Name == "id":
			return "The Stripe ID of the " + subject + "."
		default:
			return "The ID of the parent " + strings.ReplaceAll(a.Name, "_", " ") + "."
		}
	}
	list := func(heading string, keep func(*identityAttr) bool) {
		var l []string
		// The parent attribute comes before the object's own ID.
		for _, pass := range []bool{false, true} {
			for _, a := range ids {
				if keep(a) && (a.Name == "id") == pass {
					l = append(l, fmt.Sprintf("* `%s` (%s) %s", a.Name, a.Type, describe(a)))
				}
			}
		}
		if len(l) > 0 {
			m.add("#### " + heading)
			m.add(strings.Join(l, "\n"))
		}
	}
	list("Required", func(a *identityAttr) bool { return a.Required })
	list("Optional", func(a *identityAttr) bool { return !a.Required })
}
